// Writes src/contract.ts from the JSON Schemas in ../contract. One wrapper schema so shared types are declared once.
import { readdirSync, writeFileSync } from "node:fs";
import { compile } from "json-schema-to-typescript";

const dir = new URL("../../contract/", import.meta.url);
const files = readdirSync(dir).filter((f) => f.endsWith(".schema.json") && f !== "common.schema.json");
const wrapper = {
  title: "Contract",
  type: "object",
  additionalProperties: false,
  properties: Object.fromEntries(files.map((f) => [f.replace(".schema.json", ""), { $ref: f }])),
  required: files.map((f) => f.replace(".schema.json", "")),
};
const ts = await compile(wrapper, "Contract", {
  cwd: decodeURIComponent(dir.pathname).replace(/^\/([A-Za-z]:)/, "$1"),
  bannerComment: "// Generated by `npm run types` from contract/*.schema.json. Do not edit.",
  ignoreMinAndMaxItems: true,
  additionalProperties: false,
});
writeFileSync(new URL("../src/contract.ts", import.meta.url), ts);
console.log(`src/contract.ts from ${files.length} schemas`);
